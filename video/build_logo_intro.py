"""Generate the logo intro mp4 — mark fade in, then equal-weight wordmark fade in."""
import cairosvg, subprocess, os
from pathlib import Path

FPS = 24
DUR = 13.0
TOTAL_FRAMES = int(FPS * DUR)  # 180
HERE = Path(__file__).resolve().parent
FRAMES_DIR = HERE / "_intro_frames_tmp"
FRAMES_DIR.mkdir(exist_ok=True)
OUT_MP4 = HERE / "clips" / "logo_intro.mp4"
OUT_MP4.parent.mkdir(exist_ok=True)

# Timing:
#   0.0 → 2.0  : mark fade in (opacity 0 → 1)
#   2.0 → 2.5  : mark held
#   2.5 → 4.0  : wordmark fade in (opacity 0 → 1)
#   4.0 → 7.5  : full lockup held
MARK_FADE_END = 2.0
WORD_FADE_START = 2.5
WORD_FADE_END = 4.0

def opacity_curves(t):
    mark = min(1.0, t / MARK_FADE_END) if t < MARK_FADE_END else 1.0
    if t < WORD_FADE_START:
        word = 0.0
    elif t < WORD_FADE_END:
        word = (t - WORD_FADE_START) / (WORD_FADE_END - WORD_FADE_START)
    else:
        word = 1.0
    return mark, word

