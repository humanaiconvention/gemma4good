print(f"rendering {TOTAL_FRAMES} frames…")
for i in range(TOTAL_FRAMES):
    t = i / FPS
    mark_o, word_o = opacity_curves(t)
    svg = make_svg(mark_o, word_o)
    png = FRAMES_DIR / f"f{i:04d}.png"
